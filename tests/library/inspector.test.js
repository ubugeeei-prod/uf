describe("a document that arrived whole", () => {
  it("is not a stream, whatever its chunk count", () => {
    // The bytes of a big document reach a socket in pieces, and none of that is
    // a boundary resolving. Reporting it would turn this into a request log.
    const time = clock();
    const recorder = inspectStream(time.now);
    recorder.chunk('<div id="uf-root"><p>a</p>');
    time.wind(2);
    recorder.chunk("<p>b</p></div>");

    expect(didStream(recorder.finish())).toBe(false);
  });
});

