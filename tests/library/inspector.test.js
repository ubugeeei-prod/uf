/** A record of one shell and two completions, for the wording tests. */
function twoBoundaries(): StreamRecord {
  const time = clock();
  const recorder = inspectStream(time.now);
  recorder.chunk(SHELL);
  time.wind(119);
  recorder.chunk(completion(0, '<article class="post">the post</article>'));
  time.wind(122);
  recorder.chunk(completion(1, '<section id="two">two</section>'));
  return recorder.finish();
}

describe("the report", () => {
  it("names the boundaries, how late each was, and what each replaced", () => {
    const { message, detail } = formatStream("/docs/:slug", twoBoundaries());

    expect(message).toBe("/docs/:slug streamed 2 boundaries after its shell, the last 241 ms in");
    expect(detail[0]).toContain("the shell went out in");
    expect(detail[0]).toContain("2 fallbacks in it");
    expect(detail[1]).toContain("+119 ms");
    expect(detail[1]).toContain("B:0 replaced p.loading with article.post");
    expect(detail[1]).toContain("chunk 2 of 3");
    expect(detail[2]).toContain("+241 ms");
    expect(detail[2]).toContain("B:1 replaced p.loading-two with section#two");
  });

  it("scrubs a label the page controls", () => {
    // The fallback is the application's own markup and this line goes to a
    // terminal. `@uniflowed/vite`'s `internal/diagnostics.js` scrubs what
    // arrives on the browser channel; this report never goes through it.
    const time = clock();
    const recorder = inspectStream(time.now);
    recorder.chunk(
      `<!--$?--><template id="B:0"></template><p class="load\u001b[31mer">x</p><!--/$-->`,
    );
    recorder.chunk(completion(0, `<p class="out\u001b[0m">done</p>`));

    const { detail } = formatStream("/x", recorder.finish());
    expect(detail[1]).not.toContain("\u001b");
    expect(detail[1]).toContain("p.load [31mer");
    expect(detail[1]).toContain("p.out [0m");
  });
});

