// ---------------------------------------------------------------------------
// React's wire format, written out
// ---------------------------------------------------------------------------

/**
 * The shell of a document with two boundaries suspended in it.
 *
 * Exactly what React 19.2.8 writes, with the fallbacks a `$loading.js` would
 * have rendered: an empty `<template id="B:n">`, the fallback, and the comment
 * that closes the boundary.
 */
const SHELL =
  '<div id="uf-root"><nav class="masthead">nav</nav>' +
  '<!--$?--><template id="B:0"></template><p class="loading">Loading the post…</p><!--/$-->' +
  "<hr/>" +
  '<!--$?--><template id="B:1"></template><p class="loading-two">Loading two</p><!--/$-->' +
  '<footer class="colophon">footer</footer></div>';

/** A completion, as React writes one: the content hidden, then the swap. */
function completion(index: number, content: string): string {
  return (
    `<div hidden id="S:${index}">${content}</div>` +
    `<script>$RC("B:${index}","S:${index}")</script>`
  );
}

/** A clock a test winds by hand. */
function clock(): {| readonly now: () => number, readonly wind: (ms: number) => void |} {
  let at = 1000;
  return {
    now: () => at,
    wind: (ms: number) => {
      at += ms;
    },
  };
}

describe("recording a stream", () => {
  it("numbers the chunks, times them from the shell, and counts their bytes", () => {
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    time.wind(119);
    recorder.chunk(completion(0, '<article class="post">the post</article>'));
    time.wind(122);
    recorder.chunk(completion(1, '<section id="two">two</section>'));
    const record = recorder.finish();

    expect(record.chunks.map((chunk) => chunk.index)).toEqual([1, 2, 3]);
    // From the first chunk, not from the recorder: the shell is what the
    // browser has been looking at, so every later arrival is measured against
    // the moment it got one.
    expect(record.chunks.map((chunk) => chunk.at)).toEqual([0, 119, 241]);
    // Bytes of UTF-8 rather than characters, because that is what the socket
    // carried. The shell has a `…` in it, which is three of them and one of
    // these.
    expect(record.bytes).toBe(
      new TextEncoder().encode(
        SHELL +
          completion(0, '<article class="post">the post</article>') +
          completion(1, '<section id="two">two</section>'),
      ).length,
    );
    expect(record.chunks[0].bytes).toBeGreaterThan(SHELL.length);
  });

  it("says which boundary each chunk completed, and what it built", () => {
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    time.wind(119);
    recorder.chunk(completion(0, '<article class="post">the post</article>'));
    const record = recorder.finish();

    expect(record.chunks[0].boundaries).toEqual([]);
    expect(record.chunks[1].boundaries).toEqual([
      { id: "B:0", fallback: "p.loading", built: ["article.post"], more: 0 },
    ]);
  });

  it("attributes two boundaries that completed in the same chunk, in order", () => {
    // React coalesces completions that become ready together, so one chunk
    // carrying two is the ordinary case rather than the exotic one — and a
    // reader who is told "one chunk" about two boundaries has been told the
    // wrong thing about the order.
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    time.wind(40);
    recorder.chunk(
      completion(1, '<section id="two">two</section>') +
        completion(0, '<article class="post">the post</article>'),
    );

    expect(recorder.finish().chunks[1].boundaries.map((boundary) => boundary.id)).toEqual([
      "B:1",
      "B:0",
    ]);
  });

  it("names the elements a boundary built and counts the rest", () => {
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    recorder.chunk(
      completion(
        0,
        '<h1 id="title">t</h1><p class="lede a">l</p><img src="x"/><span>s</span><b>b</b>',
      ),
    );

    const [boundary] = recorder.finish().chunks[1].boundaries;
    expect(boundary.built).toEqual(["h1#title", "p.lede", "img"]);
    expect(boundary.more).toBe(2);
  });

  it("names what the boundary owns rather than everything inside it", () => {
    // One `<article>` with forty paragraphs in it built one thing. A reader
    // told about the forty has been told less, not more.
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    recorder.chunk(
      completion(
        0,
        '<article class="post"><h2>h</h2><p>a</p><div><p>b</p><span>c</span></div></article>',
      ),
    );

    expect(recorder.finish().chunks[1].boundaries[0].built).toEqual(["article.post"]);
  });

  it("reports a chunk it cannot attribute rather than dropping it", () => {
    // A `$RC(` split across two chunks is not attributed, and the bytes and the
    // position are still the truth. Saying nothing about the boundary is the
    // honest failure; inventing one is not.
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk(SHELL);
    time.wind(15);
    recorder.chunk('<div hidden id="S:0"><article class="post">the post</article></div><scr');
    const record = recorder.finish();

    expect(record.chunks.length).toBe(2);
    expect(record.chunks[1].at).toBe(15);
    expect(record.chunks[1].boundaries).toEqual([]);
    expect(didStream(record)).toBe(false);
  });

  it("leaves the fallback null for a boundary the shell never named", () => {
    const time = clock();
    const recorder = inspectStream(time.now);

    recorder.chunk('<div id="uf-root"><p>no boundary was declared here</p></div>');
    recorder.chunk(completion(7, "<p>late</p>"));

    expect(recorder.finish().chunks[1].boundaries).toEqual([
      { id: "B:7", fallback: null, built: ["p"], more: 0 },
    ]);
  });

  it("counts the chunks past its own limit instead of holding them", () => {
    const time = clock();
    const recorder = inspectStream(time.now);
    for (let index = 0; index < 70; index += 1) {
      recorder.chunk(completion(index, "<p>x</p>"));
    }
    const record = recorder.finish();

    // `docs/security.md`'s rule: a report has no unbounded anything in it, and
    // a document is something a page can make arbitrarily long.
    expect(record.chunks.length).toBe(64);
    expect(record.more).toBe(6);
  });
});

