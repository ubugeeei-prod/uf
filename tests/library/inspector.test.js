describe("the shape React actually writes", () => {
  it("still opens a boundary with a template and closes it with `$RC(`", async () => {
    // The parsing tests above are pinned to bytes written out by hand, which is
    // what makes them readable and what makes them unable to notice React
    // changing its wire format. This is the other half: a real render, and the
    // two markers `internal/inspector.js` keys on.
    const waited = deferred();
    const renderer = createRenderer({
      App: routerView("./app"),
      ...suspendingTable(waited.promise),
    });
    setTimeout(() => waited.resolve(), 20);

    const document = await (await renderer.render("/slow", assets)).text();

    expect(document).toContain('<template id="B:');
    expect(document).toContain("<!--/$-->");
    expect(document).toContain('$RC("B:');
    expect(document).toContain('id="S:');
  });
});
