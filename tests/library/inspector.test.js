describe("a host that asked for nothing", () => {
  it("gets the chunks it would have got, and no recorder is built", async () => {
    // `inspected` is the only path into this module from `./stream.js`, and
    // `stream.js` does not call it without an `onStream`. The claim here is the
    // weaker, checkable half: passing chunks through changes none of them.
    const seen: Array<string> = [];
    async function* three(): AsyncGenerator<string, void, void> {
      yield "a";
      yield "b";
      yield "c";
    }
    const out = [];
    for await (const chunk of inspected(
      three(),
      (record) => {
        seen.push(String(record.bytes));
      },
      () => Date.now(),
    )) {
      out.push(chunk);
    }

    expect(out).toEqual(["a", "b", "c"]);
    expect(seen).toEqual(["3"]);
  });

  it("reports what was sent when the consumer gives up partway", async () => {
    // A browser that navigates away closes the socket, and what it got before
    // it did is the interesting half of that.
    let record: StreamRecord | null = null;
    async function* many(): AsyncGenerator<string, void, void> {
      yield SHELL;
      yield completion(0, "<p>one</p>");
      yield completion(1, "<p>two</p>");
    }
    const stream = inspected(
      many(),
      (finished) => {
        record = finished;
      },
      () => Date.now(),
    );
    await stream.next();
    await stream.next();
    await stream.return(undefined);

    expect(record).not.toBe(null);
    expect(record?.chunks.length).toBe(2);
  });
});

