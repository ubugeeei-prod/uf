describe("naming an element", () => {
  it("spells a tag the way `boundaries.js` spells the element", () => {
    // The stream report and the boundary report are about the same page, and a
    // reader should not have to learn that `article.post` means the same thing
    // in both. They cannot share an implementation — one is handed a DOM node
    // and the other a string of markup — so the spellings are held together
    // here instead, which is the same arrangement `devtools.test.js` has for
    // `DEVTOOLS_HOOK`.
    const document = globalThis.document ?? render(<div />).container.ownerDocument;
    const cases = [
      ['<section id="shell" class="wide dark">', "section", { id: "shell", class: "wide dark" }],
      ['<article class="post featured">', "article", { class: "post featured" }],
      ["<p>", "p", {}],
    ];

    for (const [tag, name, attributes] of cases) {
      const element = document.createElement(String(name));
      for (const [key, value] of Object.entries(attributes)) {
        element.setAttribute(key, String(value));
      }
      expect(describeTag(String(tag))).toBe(describeElement(element));
    }
  });

  it("reads a self-closed tag as one element", () => {
    expect(describeTag('<img class="hero"/>')).toBe("img.hero");
  });
});

