// @flow
//
// What left, in what order, and what each chunk built.
//
// ubugeeei-prod/uf#520 asks for an inspector for the payload. uf has no Flight
// payload — `packages/router/client.js` re-renders the matched tree from the
// same modules the server used, and ubugeeei-prod/uf#519 is where a payload is
// being worked out — but it does stream a document whose Suspense boundaries
// resolve one at a time, and the issue's three questions are questions about
// that. So this is a test about the stream that exists.
//
// It has two halves and the split matters. The first drives the recorder over
// React's wire format written out by hand, because the claims about *parsing*
// have to be pinned to bytes a reader can see in the test — a fixture that is
// generated by the same React the code reads would agree with itself no matter
// what either of them did. Those bytes are not invented: they were taken from a
// `renderToPipeableStream` of two boundaries resolving 120 ms apart, and
// `the shape React actually writes` below renders a real one and asserts the
// markers are still there, so the day React changes them is a failing test
// rather than a report that quietly stops naming anything.
//
// The second half drives a real `createRenderer` over a route that suspends,
// which is the only thing that proves the recorder is looking at the bytes a
// host is handed rather than at some earlier draft of them: the head is
// inserted, `transformHead` has run, and the chunk boundaries are React's.
//
// The module is internal to `@uniflowed/router` and is reached by path, the way
// `boundaries.test.js` reaches `internal/boundaries.js`.

