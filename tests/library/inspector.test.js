describe("when it speaks", () => {
  it("speaks the first time a path streams", () => {
    // Which is the moment the answer changed: you have just written the
    // `$loading.js`, or the `await` that made the page suspend.
    const sent: Array<StreamDiagnostic> = [];
    streamReporter("/slow", (report) => {
      sent.push(report);
    })(twoBoundaries());

    expect(sent.length).toBe(1);
    expect(sent[0].message).toContain("/slow streamed 2 boundaries after its shell");
  });

  it("says nothing when the same path streams the same way again", () => {
    const sent: Array<StreamDiagnostic> = [];
    const report = streamReporter("/slow", (entry) => {
      sent.push(entry);
    });
    report(twoBoundaries());
    report(twoBoundaries());

    expect(sent.length).toBe(1);
  });

  it("says nothing when only the timings moved", () => {
    // A page whose data got slower has not changed shape, and a report that
    // fired on the milliseconds would fire on every reload.
    const sent: Array<StreamDiagnostic> = [];
    const report = streamReporter("/slow", (entry) => {
      sent.push(entry);
    });
    report(twoBoundaries());

    const time = clock();
    const slower = inspectStream(time.now);
    slower.chunk(SHELL);
    time.wind(900);
    slower.chunk(completion(0, '<article class="post">the post</article>'));
    time.wind(900);
    slower.chunk(completion(1, '<section id="two">two</section>'));
    report(slower.finish());

    expect(sent.length).toBe(1);
  });

  it("speaks again when a boundary is added", () => {
    const sent: Array<StreamDiagnostic> = [];
    const report = streamReporter("/slow", (entry) => {
      sent.push(entry);
    });

    const time = clock();
    const one = inspectStream(time.now);
    one.chunk(SHELL);
    one.chunk(completion(0, '<article class="post">the post</article>'));
    report(one.finish());
    report(twoBoundaries());

    expect(sent.length).toBe(2);
    expect(sent[1].message).toContain("2 boundaries");
  });

  it("says nothing at all about a document that did not stream", () => {
    const sent: Array<StreamDiagnostic> = [];
    const time = clock();
    const recorder = inspectStream(time.now);
    recorder.chunk('<div id="uf-root"><p>whole</p></div>');
    streamReporter("/plain", (report) => {
      sent.push(report);
    })(recorder.finish());

    expect(sent).toEqual([]);
  });

  it("keeps one path's history out of another's", () => {
    const sent: Array<StreamDiagnostic> = [];
    streamReporter("/a", (report) => {
      sent.push(report);
    })(twoBoundaries());
    streamReporter("/b", (report) => {
      sent.push(report);
    })(twoBoundaries());

    expect(sent.map((entry) => entry.message.split(" ")[0])).toEqual(["/a", "/b"]);
  });
});

describe("the signature", () => {
  it("holds the boundaries and their chunk, and not the clock", () => {
    const one = streamSignature(twoBoundaries());
    const time = clock();
    const slower = inspectStream(time.now);
    slower.chunk(SHELL);
    time.wind(2000);
    slower.chunk(completion(0, '<article class="post">the post</article>'));
    time.wind(2000);
    slower.chunk(completion(1, '<section id="two">two</section>'));

    expect(streamSignature(slower.finish())).toBe(one);
    expect(one).toContain("B:0");
    expect(one).toContain("article.post");
    expect(one).not.toContain("119");
  });
});

